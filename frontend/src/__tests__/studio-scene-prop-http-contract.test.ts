// @vitest-environment happy-dom
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { activateRuntimeEnvironment, clearRuntimeEnvironment, requireActiveRuntimeEnvironment } from '@/lib/runtimeEnvironment';
import { validateStudioAssetImageReceipt } from '@/lib/studioAssetImageContract';
import { listStudioAssetImageRequests, readStudioAssetImageRequestReceipt, submitStudioAssetImageRequest } from '@/lib/studioAssetImageRequest';
import fixture from './fixtures/studio-scene-prop-http.json';

vi.mock('@/lib/appAccess', () => ({ appAccessFetch: (...args: Parameters<typeof fetch>) => fetch(...args) }));

beforeEach(() => {
    localStorage.clear();
    clearRuntimeEnvironment();
    activateRuntimeEnvironment({ schema_version: 1, storage_id: '11111111-1111-4111-8111-111111111111' });
    vi.stubGlobal('navigator', { locks: { request: async (_name: string, _opts: unknown, callback: (lock: object) => unknown) => callback({}) } });
});
afterEach(() => { clearRuntimeEnvironment(); vi.unstubAllGlobals(); });

// Generated by actual backend HTTP tests; provider transport alone is an offline substitute.
it.each(Object.entries(fixture))('accepts backend %s receipts and retains one original request across GET recovery', async (_name, value) => {
    const initial = validateStudioAssetImageReceipt(value.initial);
    const terminal = validateStudioAssetImageReceipt(value.terminal);
    const replay = validateStudioAssetImageReceipt(value.replay);
    expect(initial).toEqual(value.initial);
    expect(terminal).toEqual(value.terminal);
    expect(replay.request).toEqual(terminal.request);
    const { client_request_id: key, asset_type: kind, generation_type: channel, ...input } = value.command;
    if ((kind !== 'scene' && kind !== 'prop') || channel !== 'all') throw new Error('invalid generated fixture command');
    const options = {
        environment: requireActiveRuntimeEnvironment(), rootKind: initial.request.request_root_kind,
        rootId: initial.request.request_root_id, storage: localStorage,
    };
    const requests: string[] = [];
    const net = vi.fn(async (url: string, init: RequestInit) => {
        requests.push(init.method!);
        if (init.method === 'POST') {
            expect(JSON.parse(String(init.body))).toEqual(value.command);
            expect(listStudioAssetImageRequests(options)[0].request).toEqual(value.command);
        } else {
            expect(url.endsWith(`/asset_image_requests/${key}`)).toBe(true);
            expect(init.body).toBeUndefined();
        }
        return new Response(JSON.stringify(init.method === 'POST' ? value.initial : value.terminal));
    });
    vi.stubGlobal('fetch', net);
    const sent = await submitStudioAssetImageRequest({ ...options, input: { ...input, asset_type: kind, generation_type: channel }, idFactory: () => key });
    expect(sent.status).toBe('confirmed');
    expect(sent.receipt).toEqual(initial);
    const recovered = await readStudioAssetImageRequestReceipt({ ...options, journal: sent.journal });
    expect(recovered.status).toBe('confirmed');
    expect(recovered.receipt).toEqual(terminal);
    expect(recovered.journal.request).toEqual(value.command);
    expect(recovered.journal.receiptIdentity).toBe(sent.journal.receiptIdentity);
    expect(listStudioAssetImageRequests(options)).toHaveLength(1);
    expect(requests).toEqual(['POST', 'GET']);
});
